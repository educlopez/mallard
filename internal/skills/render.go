package skills

import (
	"fmt"
	"os"
	"path/filepath"
	"strconv"
	"strings"

	"github.com/educlopez/mallard/internal/agents"
)

// GeneratedDir is the hidden folder under the source root where mallard writes
// per-agent renderings of claude/agents/*.md. Living under the source root keeps
// the links "managed" for doctor/uninstall (their targets resolve inside it).
const GeneratedDir = ".generated"

// AgentsFor returns the agent items to link for agentID.
//
// Claude Code (and the agents without an agents dir) get the source markdown
// as-is. Codex, OpenCode and Cursor use a different file format or frontmatter,
// so a rendered copy is written to <repoRoot>/.generated/<agentID>/agents/ and
// the returned items point there. With write=false nothing touches disk and the
// returned paths are where the files would be written (dry runs).
func AgentsFor(repoRoot, agentID string, src []Skill, write bool) ([]Skill, error) {
	render, ext := rendererFor(agentID)
	if render == nil || len(src) == 0 {
		return src, nil
	}

	outDir := filepath.Join(repoRoot, GeneratedDir, agentID, "agents")
	if write {
		// Wipe first so removed source agents do not leave stale renderings.
		if err := os.RemoveAll(outDir); err != nil {
			return nil, fmt.Errorf("clean %s: %w", outDir, err)
		}
		if err := os.MkdirAll(outDir, 0o755); err != nil {
			return nil, fmt.Errorf("create %s: %w", outDir, err)
		}
	}

	out := make([]Skill, 0, len(src))
	for _, s := range src {
		base := strings.TrimSuffix(s.Name, filepath.Ext(s.Name))
		dst := filepath.Join(outDir, base+ext)
		if write {
			data, err := os.ReadFile(s.SrcPath)
			if err != nil {
				return nil, fmt.Errorf("read %s: %w", s.SrcPath, err)
			}
			fm, body := splitFrontmatter(string(data))
			if fm["name"] == "" {
				fm["name"] = base
			}
			if err := os.WriteFile(dst, []byte(render(fm, body)), 0o644); err != nil {
				return nil, fmt.Errorf("write %s: %w", dst, err)
			}
		}
		out = append(out, Skill{Name: base + ext, SrcPath: dst})
	}
	return out, nil
}

type renderFunc func(fm map[string]string, body string) string

func rendererFor(agentID string) (renderFunc, string) {
	switch agentID {
	case agents.IDCodex:
		return renderCodex, ".toml"
	case agents.IDOpenCode:
		return renderOpenCode, ".md"
	case agents.IDCursor:
		return renderCursor, ".md"
	}
	return nil, ""
}

// renderCodex emits a Codex custom-agent TOML file. Claude model aliases
// (sonnet, opus) mean nothing to Codex, so model is left to the parent session.
// Codex does not let an agent file override the sandbox, so tools are dropped.
func renderCodex(fm map[string]string, body string) string {
	var b strings.Builder
	b.WriteString("# Generated by mallard from claude/agents. Do not edit.\n")
	fmt.Fprintf(&b, "name = %s\n", tomlString(strings.ReplaceAll(fm["name"], "-", "_")))
	fmt.Fprintf(&b, "description = %s\n", tomlString(fm["description"]))
	fmt.Fprintf(&b, "developer_instructions = %s\n", tomlMultiline(body))
	return b.String()
}

// renderOpenCode emits an OpenCode subagent. The Claude tools allowlist maps to
// permission denies for edit and bash; model and color are dropped because
// OpenCode expects provider/model ids and hex or theme colours.
func renderOpenCode(fm map[string]string, body string) string {
	var b strings.Builder
	b.WriteString("---\n")
	fmt.Fprintf(&b, "description: %s\n", yamlString(fm["description"]))
	b.WriteString("mode: subagent\n")
	tools, restricted := toolSet(fm["tools"])
	if restricted && (!tools["edit"] || !tools["bash"]) {
		b.WriteString("permission:\n")
		if !tools["edit"] {
			b.WriteString("  edit: deny\n")
		}
		if !tools["bash"] {
			b.WriteString("  bash: deny\n")
		}
	}
	b.WriteString("---\n")
	b.WriteString(body)
	return b.String()
}

// renderCursor emits a Cursor subagent. The model follows the parent session;
// an agent whose Claude tools allowlist has no edit tool becomes readonly.
func renderCursor(fm map[string]string, body string) string {
	var b strings.Builder
	b.WriteString("---\n")
	fmt.Fprintf(&b, "name: %s\n", yamlString(fm["name"]))
	fmt.Fprintf(&b, "description: %s\n", yamlString(fm["description"]))
	b.WriteString("model: inherit\n")
	if tools, restricted := toolSet(fm["tools"]); restricted && !tools["edit"] {
		b.WriteString("readonly: true\n")
	}
	b.WriteString("---\n")
	b.WriteString(body)
	return b.String()
}

// toolSet reduces a Claude "tools: Read, Edit, Bash" allowlist to capability
// flags. restricted is false when no allowlist is set (the agent gets every
// tool).
func toolSet(raw string) (caps map[string]bool, restricted bool) {
	caps = map[string]bool{}
	raw = strings.Trim(strings.TrimSpace(raw), "[]")
	if raw == "" {
		return caps, false
	}
	for _, t := range strings.Split(raw, ",") {
		switch strings.Trim(strings.TrimSpace(t), `"'`) {
		case "Edit", "Write", "MultiEdit", "NotebookEdit":
			caps["edit"] = true
		case "Bash":
			caps["bash"] = true
		}
	}
	return caps, true
}

// splitFrontmatter returns top-level scalar frontmatter keys and the body that
// follows the closing "---". Indented (nested or folded) lines extend the
// previous key's value; nested maps such as metadata are flattened and unused.
func splitFrontmatter(text string) (map[string]string, string) {
	fm := map[string]string{}
	text = strings.ReplaceAll(text, "\r\n", "\n")
	if !strings.HasPrefix(text, "---\n") {
		return fm, text
	}
	rest := text[len("---\n"):]
	end := strings.Index(rest, "\n---")
	if end == -1 {
		return fm, text
	}
	header := rest[:end]
	body := rest[end+len("\n---"):]
	if i := strings.IndexByte(body, '\n'); i != -1 {
		body = body[i+1:]
	} else {
		body = ""
	}
	body = strings.TrimLeft(body, "\n")

	var key string
	for _, line := range strings.Split(header, "\n") {
		if strings.TrimSpace(line) == "" {
			continue
		}
		if line[0] == ' ' || line[0] == '\t' {
			if key != "" {
				fm[key] = strings.TrimSpace(fm[key] + " " + strings.TrimSpace(line))
			}
			continue
		}
		k, v, ok := strings.Cut(line, ":")
		if !ok {
			key = ""
			continue
		}
		key = strings.TrimSpace(k)
		v = strings.TrimSpace(v)
		if v == ">" || v == "|" || v == ">-" || v == "|-" {
			v = ""
		}
		fm[key] = unquoteYAML(v)
	}
	return fm, body
}

func unquoteYAML(v string) string {
	if len(v) >= 2 {
		switch {
		case v[0] == '"' && v[len(v)-1] == '"':
			if u, err := strconv.Unquote(v); err == nil {
				return u
			}
			return v[1 : len(v)-1]
		case v[0] == '\'' && v[len(v)-1] == '\'':
			return strings.ReplaceAll(v[1:len(v)-1], "''", "'")
		}
	}
	return v
}

// yamlString renders s as a YAML double-quoted scalar. Go's quoting escapes are
// a subset of YAML's, so the output is always valid YAML.
func yamlString(s string) string { return strconv.Quote(s) }

// tomlString renders s as a TOML basic string.
func tomlString(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for _, r := range s {
		switch r {
		case '\\':
			b.WriteString(`\\`)
		case '"':
			b.WriteString(`\"`)
		case '\n':
			b.WriteString(`\n`)
		case '\t':
			b.WriteString(`\t`)
		case '\r':
			b.WriteString(`\r`)
		default:
			if r < 0x20 || r == 0x7f {
				fmt.Fprintf(&b, `\u%04X`, r)
			} else {
				b.WriteRune(r)
			}
		}
	}
	b.WriteByte('"')
	return b.String()
}

// tomlMultiline renders s as a TOML multi-line basic string. Backslashes and
// double quotes are escaped so no sequence in s can end the string early.
func tomlMultiline(s string) string {
	var b strings.Builder
	b.WriteString("\"\"\"\n")
	for _, r := range s {
		switch r {
		case '\\':
			b.WriteString(`\\`)
		case '"':
			b.WriteString(`\"`)
		case '\n', '\t':
			b.WriteRune(r)
		case '\r':
			// dropped: CRLF already normalised
		default:
			if r < 0x20 || r == 0x7f {
				fmt.Fprintf(&b, `\u%04X`, r)
			} else {
				b.WriteRune(r)
			}
		}
	}
	if !strings.HasSuffix(s, "\n") {
		b.WriteByte('\n')
	}
	b.WriteString(`"""`)
	return b.String()
}
